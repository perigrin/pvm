// ABOUTME: Generates and holds testdata/latency/edit5k.pl, the 5 kLOC file M2's latency benchmarks parse and edit.
// ABOUTME: Original T0 code (plan §3.2: nothing vendored); the committed file must equal the generator's output.

package psc

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"tamarou.com/pvm/internal/parse"
	"tamarou.com/pvm/internal/perltest"
)

var updateLatencyFixture = flag.Bool("psc.update-latency-fixture", false,
	"rewrite testdata/latency/edit5k.pl from latencyFixture")

// latencyFixturePath is the 5 kLOC fixture spec chapter 6 §6.10 budgets a
// 1-char edit against.
var latencyFixturePath = filepath.Join("testdata", "latency", "edit5k.pl")

// latencyFixtureLines is the plan's file size for M2's latency gate (plan
// §5 M2: "5 kLOC file, 1-char edit").
const latencyFixtureLines = 5000

// latencyBlock is one package's worth of the fixture. %[1]d is the block's
// index, so no two blocks share a name. It mixes what a module carries:
// signatures, lexical and package hashes, arrow chains, a heredoc, regexes,
// sort/map/grep, string ops, a closure, a method call and POD.
const latencyBlock = `package Fixture::Block%[1]d;

use strict;
use warnings;

our $VERSION = '0.%[1]03d';
our %%REGISTRY;

my %%defaults = (
    name    => 'block%[1]d',
    limit   => %[1]d,
    ratio   => 0.%[1]d,
    tags    => [qw(alpha beta gamma)],
);

sub new {
    my ($class, %%args) = @_;
    my $self = { %%defaults, %%args };
    $REGISTRY{ $self->{name} } = $self;
    return bless $self, $class;
}

sub limit { $_[0]->{limit} }

sub describe {
    my ($self) = @_;
    my $text = <<"END";
Block %[1]d: $self->{name}
  limit=$self->{limit} tags=@{ $self->{tags} }
END
    return $text;
}

sub scale {
    my ($self, @values) = @_;
    my @kept = grep { defined && $_ > 0 } @values;
    my @scaled = map { $_ * $self->{ratio} } sort { $a <=> $b } @kept;
    return wantarray ? @scaled : scalar @scaled;
}

sub classify {
    my ($self, $word) = @_;
    return 'empty' unless length $word;
    if ($word =~ /^(\d+)(?:\.(\d+))?$/) {
        return $2 ? "float:$1.$2" : "int:$1";
    }
    (my $clean = lc $word) =~ s/[^a-z0-9]+/_/g;
    return exists $REGISTRY{$clean} ? "known:$clean" : "word:$clean";
}

sub counter {
    my $count = %[1]d;
    return sub { $count += @_ ? shift : 1; return $count };
}

sub report {
    my ($self, $out) = @_;
    my $n = 0;
    for my $key (sort keys %%$self) {
        next if ref $self->{$key};
        printf {$out} "%%-8s %%s\n", $key, $self->{$key};
        last if ++$n >= $self->limit;
    }
    return $n;
}

=head2 Block%[1]d

C<new>, C<describe>, C<scale>, C<classify>, C<counter> and C<report>.

=cut

`

// latencyFixture is the fixture's text: blocks until it reaches
// latencyFixtureLines, then a main package that uses the last block.
func latencyFixture() []byte {
	var b strings.Builder
	b.WriteString("#!/usr/bin/perl\n# Generated by internal/psc/latency_fixture_test.go; do not edit by hand.\n\n")
	n := 0
	for strings.Count(b.String(), "\n") < latencyFixtureLines-12 {
		fmt.Fprintf(&b, latencyBlock, n)
		n++
	}
	fmt.Fprintf(&b, `package main;

my $obj = Fixture::Block%[1]d->new(name => 'main');
my $next = Fixture::Block%[1]d::counter();
$next->() for 1 .. 3;
print $obj->describe;
print join(',', $obj->scale(3, 1, 2)), "\n";
print $obj->classify('Hello World'), "\n";
$obj->report(\*STDOUT);

1;
`, n-1)
	return []byte(b.String())
}

// TestLatencyFixtureMatchesGenerator: the committed fixture is exactly
// what latencyFixture writes, so a benchmark's numbers name one file.
func TestLatencyFixtureMatchesGenerator(t *testing.T) {
	want := latencyFixture()
	if *updateLatencyFixture {
		if err := os.MkdirAll(filepath.Dir(latencyFixturePath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(latencyFixturePath, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(latencyFixturePath)
	if err != nil {
		t.Fatalf("%v (regenerate with -psc.update-latency-fixture)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s differs from latencyFixture's output; regenerate with -psc.update-latency-fixture", latencyFixturePath)
	}
}

// TestLatencyFixtureIs5kLOCAndParsesClean: the fixture has at least the
// plan's 5,000 lines, and internal/parse reads all of it, so the benchmark
// times real parsing and not a refusal.
func TestLatencyFixtureIs5kLOCAndParsesClean(t *testing.T) {
	src, err := os.ReadFile(latencyFixturePath)
	if err != nil {
		t.Fatal(err)
	}
	if n := bytes.Count(src, []byte("\n")); n < latencyFixtureLines {
		t.Errorf("%s has %d lines, want at least %d", latencyFixturePath, n, latencyFixtureLines)
	}
	if n := unknowns(parse.Parse(src)); n != 0 {
		t.Errorf("%s parses with %d Unknown node(s), want 0", latencyFixturePath, n)
	}
}

// TestLatencyFixtureCompiles: perl compiles the fixture, so it is Perl and
// not something only internal/parse accepts.
func TestLatencyFixtureCompiles(t *testing.T) {
	p := perltest.Perl542(t)
	out, err := p.Command("-c", latencyFixturePath).CombinedOutput()
	if err != nil {
		t.Fatalf("perl -c %s: %v\n%s", latencyFixturePath, err, out)
	}
}

// unknowns counts the Unknown nodes under n.
func unknowns(n *parse.Node) int {
	total := 0
	if n.Kind == parse.Unknown {
		total = 1
	}
	for _, c := range n.Children {
		total += unknowns(c)
	}
	return total
}
