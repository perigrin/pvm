// ABOUTME: Generates and holds testdata/std5k.pl, the 5 kLOC Standard Perl file the chart's speed kill measures.
// ABOUTME: Modelled on psc's latencyFixture with its own template; the committed file must equal std5k's output.

package chart

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"tamarou.com/pvm/internal/parse"
	"tamarou.com/pvm/internal/perltest"
)

var updateStd5k = flag.Bool("chart.update-std5k", false,
	"rewrite testdata/std5k.pl from std5k")

// std5kPath is the realistic input of spec §8: committed, and valid only
// while recursive descent accepts it and perl compiles it.
var std5kPath = filepath.Join("testdata", "std5k.pl")

// std5kLines is the file's floor, the same 5 kLOC as edit5k.pl.
const std5kLines = 5000

// std5kBlock is one package's worth of std5k.pl. %[1]d is the block's index,
// so no two blocks share a name. It stays inside Guacamole's Standard Perl:
// every call parenthesised, every hash key quoted, print {$fh} with braces,
// braced dereference, and no heredoc, indirect object, prototype, POD or
// bareword filehandle.
const std5kBlock = `package Std5k::Block%[1]d;

use strict;
use warnings;

our $VERSION = '0.%03[1]d';
our %%REGISTRY = ();

our %%DEFAULTS = (
    'name'  => 'block%[1]d',
    'limit' => %[1]d,
    'ratio' => 0.5,
    'tags'  => [qw(alpha beta gamma)],
);

sub new {
    my ($class, %%args) = @_;
    my $self = { %%DEFAULTS, %%args };
    $REGISTRY{ $self->{'name'} } = $self;
    return bless($self, $class);
}

sub limit {
    my ($self) = @_;
    return $self->{'limit'};
}

sub tags {
    my ($self) = @_;
    return @{ $self->{'tags'} };
}

sub scale {
    my ($self, @values) = @_;
    my @kept = grep { defined($_) && $_ > 0 } @values;
    my @scaled = map { $_ * $self->{'ratio'} } sort { $a <=> $b } @kept;
    return scalar(@scaled);
}

sub classify {
    my ($self, $word) = @_;
    if (!length($word)) {
        return 'empty';
    }
    if ($word =~ m/^(\d+)(?:\.(\d+))?$/) {
        return defined($2) ? 'float:' . $1 . '.' . $2 : 'int:' . $1;
    }
    my $clean = lc($word);
    $clean =~ s/[^a-z0-9]+/_/g;
    return exists($REGISTRY{$clean}) ? 'known:' . $clean : 'word:' . $clean;
}

sub tally {
    my ($self, @words) = @_;
    my %%seen = ();
    foreach my $word (@words) {
        my $kind = $self->classify($word);
        $seen{$kind}++;
    }
    my @counts = ();
    foreach my $kind (sort { $a cmp $b } keys(%%seen)) {
        push(@counts, $kind . '=' . $seen{$kind});
    }
    return join(',', @counts);
}

sub counter {
    my $count = %[1]d;
    return sub {
        my ($step) = @_;
        $count += defined($step) ? $step : 1;
        return $count;
    };
}

sub report {
    my ($self, $out) = @_;
    my $n = 0;
    foreach my $key (sort { $a cmp $b } keys(%%{$self})) {
        if (ref($self->{$key})) {
            next;
        }
        print {$out} sprintf('%%-8s %%s', $key, $self->{$key}), "\n";
        $n++;
        if ($n >= $self->limit()) {
            last;
        }
    }
    return $n;
}

`

// std5k is std5k.pl's text: blocks until it reaches std5kLines, then a main
// package that calls into the last block.
func std5k() []byte {
	var b strings.Builder
	b.WriteString("#!/usr/bin/perl\n# Generated by internal/chart/std5k_test.go; do not edit by hand.\n\n")
	n := 0
	for strings.Count(b.String(), "\n") < std5kLines-12 {
		fmt.Fprintf(&b, std5kBlock, n)
		n++
	}
	fmt.Fprintf(&b, `package main;

my $obj = Std5k::Block%[1]d->new('name' => 'main');
my $next = Std5k::Block%[1]d::counter();
my $out = \*STDOUT;
print {$out} $next->(2), ' ', $obj->classify('Hello World'), "\n";
print {$out} $obj->tally('1', '2.5', 'main', 'x y'), "\n";
print {$out} $obj->scale(3, 1, 2), ' ', join(',', $obj->tags()), "\n";
$obj->report($out);

1;
`, n-1)
	return []byte(b.String())
}

// TestStd5kMatchesGenerator: the committed std5k.pl is exactly what std5k
// writes, so a speed ratio names one file.
func TestStd5kMatchesGenerator(t *testing.T) {
	want := std5k()
	if *updateStd5k {
		if err := os.MkdirAll(filepath.Dir(std5kPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(std5kPath, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(std5kPath)
	if err != nil {
		t.Fatalf("%v (regenerate with -chart.update-std5k)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s differs from std5k's output; regenerate with -chart.update-std5k", std5kPath)
	}
}

// TestStd5kIs5kLOCAndParsesClean: std5k.pl has at least 5,000 lines and
// recursive descent refuses no node in it, so the speed ratio divides by real
// parsing and not by a refusal.
func TestStd5kIs5kLOCAndParsesClean(t *testing.T) {
	src, err := os.ReadFile(std5kPath)
	if err != nil {
		t.Fatal(err)
	}
	if n := bytes.Count(src, []byte("\n")); n < std5kLines {
		t.Errorf("%s has %d lines, want at least %d", std5kPath, n, std5kLines)
	}
	if n := refused(parse.Parse(src)); n != 0 {
		t.Errorf("%s parses with %d refused node(s), want 0", std5kPath, n)
	}
}

// TestStd5kHasNoCarriageReturns: std5k.pl is LF only (.gitattributes checks
// it out eol=lf), so a Windows checkout cannot change its bytes or its line
// count under TestStd5kMatchesGenerator.
func TestStd5kHasNoCarriageReturns(t *testing.T) {
	src, err := os.ReadFile(std5kPath)
	if err != nil {
		t.Fatal(err)
	}
	if n := bytes.Count(src, []byte("\r")); n != 0 {
		t.Errorf("%s holds %d carriage return(s), want 0", std5kPath, n)
	}
}

// TestStd5kCompiles: perl compiles std5k.pl, so it is Perl and not
// something only internal/parse accepts.
func TestStd5kCompiles(t *testing.T) {
	p := perltest.Perl542(t)
	out, err := p.Command("-c", std5kPath).CombinedOutput()
	if err != nil {
		t.Fatalf("perl -c %s: %v\n%s", std5kPath, err, out)
	}
}

// refused counts the refused nodes under n.
func refused(n *parse.Node) int {
	total := 0
	if n.Refused() {
		total = 1
	}
	for _, c := range n.Children {
		total += refused(c)
	}
	return total
}
